// Regenerates seed.cypher from RINF exports (semicolon-separated, unquoted CSV):
//   node docker/make-seed.mjs <directory with rinf-op.csv and rinf-sections.csv>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const AREA = { west: 14.4, east: 17.4, south: 60.0, north: 61.1 }; // Dalarna and Gävle
const STATION_TYPES = new Set(["station", "small station", "passenger stop", "passenger terminal"]);

const directory = process.argv[2];
if (!directory) throw new Error("Usage: node docker/make-seed.mjs <directory with the RINF CSV files>");

const read = (file) => {
  const [header, ...lines] = readFileSync(join(directory, file), "utf8").replace(/^﻿/, "").split(/\r?\n/).filter(Boolean);
  const columns = header.split(";");
  return lines.map((line) => Object.fromEntries(line.split(";").map((value, i) => [columns[i], value])));
};
const shortId = (uri) => uri.slice(uri.lastIndexOf("/") + 1);

const points = new Map();
for (const row of read("rinf-op.csv")) {
  const id = shortId(row.era_OperationalPoint);
  const [lon, lat] = row.era_OperationalPoint_era_netReference_geosparql_hasGeometry_geosparql_asWKT.match(/-?\d+\.\d+/g).map(Number);
  if (points.has(id) || lon < AREA.west || lon > AREA.east || lat < AREA.south || lat > AREA.north) continue;
  points.set(id, {
    rinfId: id,
    name: row.era_OperationalPoint_era_opName,
    signature: row.era_OperationalPoint_era_uopid.replace(/^SE/, ""),
    type: row.era_OperationalPoint_era_opType__label,
    lat,
    lon,
  });
}

const sections = new Map();
for (const row of read("rinf-sections.csv")) {
  const id = shortId(row.era_SectionOfLine);
  const from = points.get(shortId(row.era_SectionOfLine_era_opStart));
  const to = points.get(shortId(row.era_SectionOfLine_era_opEnd));
  if (!from || !to) continue;
  sections.set(id, {
    rinfId: id,
    from: from.rinfId,
    to: to.rinfId,
    name: `${from.name} – ${to.name}`,
    line: row.era_SectionOfLine_era_nationalLine_rdfs_label,
    lengthKm: Number(row.era_SectionOfLine_era_lengthOfSectionOfLine),
  });
}

const literal = (value) => (typeof value === "string" ? JSON.stringify(value) : String(value));
const rows = (items) =>
  items
    .sort((a, b) => a.rinfId.localeCompare(b.rinfId))
    .map((item) => `  {${Object.entries(item).map(([k, v]) => `${k}: ${literal(v)}`).join(", ")}}`)
    .join(",\n");

const nodes = (label, items) => `UNWIND [
${rows(items)}
] AS row
MERGE (n:${label} {rinfId: row.rinfId})
SET n.name = row.name, n.signature = row.signature, n.type = row.type, n.lat = row.lat, n.lon = row.lon;
`;

const all = [...points.values()];
writeFileSync(
  new URL("./seed.cypher", import.meta.url),
  `// Generated by make-seed.mjs. Do not edit.
// Railway operational points and sections of line in Dalarna and Gävle, Sweden.
// Source: European Union Agency for Railways, Register of Infrastructure (RINF), data.europa.eu/949.

${nodes("Station", all.filter((p) => STATION_TYPES.has(p.type)))}
${nodes("Junction", all.filter((p) => !STATION_TYPES.has(p.type)))}
UNWIND [
${rows([...sections.values()])}
] AS row
MATCH (a {rinfId: row.from}), (b {rinfId: row.to})
MERGE (t:TrackSection {rinfId: row.rinfId})
SET t.name = row.name, t.line = row.line, t.lengthKm = row.lengthKm
MERGE (a)-[:CONNECTS]->(t)
MERGE (t)-[:CONNECTS]->(b);
`,
);
console.log(`${all.length} operational points, ${sections.size} sections of line`);
